create or replace function public.save_lesson_document(
  p_owner_id uuid,
  p_file_id text,
  p_base_version integer,
  p_document jsonb,
  p_page_count integer,
  p_source text,
  p_run_id uuid,
  p_idempotency_key text
)
returns public.lesson_files
language plpgsql
security definer
set search_path = public
as $$
declare
  current_file public.lesson_files;
  existing_version public.lesson_file_versions;
  request_hash text;
begin
  perform public.assert_service_scope(p_owner_id);
  request_hash := encode(extensions.digest(jsonb_build_object(
    'fileId', p_file_id,
    'baseVersion', p_base_version,
    'document', p_document,
    'pageCount', p_page_count,
    'source', p_source,
    'runId', p_run_id
  )::text, 'sha256'), 'hex');

  select *
  into existing_version
  from public.lesson_file_versions
  where owner_id = p_owner_id
    and idempotency_key = p_idempotency_key;

  if found then
    if (
      existing_version.request_hash is not null
      and existing_version.request_hash <> request_hash
    ) or (
      existing_version.request_hash is null
      and (
        existing_version.lesson_file_id <> p_file_id
        or existing_version.document <> p_document
        or existing_version.page_count <> p_page_count
        or existing_version.actor <> p_source
        or existing_version.run_id is distinct from p_run_id
      )
    )
    then
      raise exception 'idempotency_conflict';
    end if;
    select *
    into current_file
    from public.lesson_files
    where owner_id = p_owner_id and id = p_file_id;
    return current_file;
  end if;

  select *
  into current_file
  from public.lesson_files
  where owner_id = p_owner_id and id = p_file_id
  for update;
  if not found then raise exception 'lesson_file_not_found'; end if;
  if current_file.document_version <> p_base_version then raise exception 'stale_document'; end if;

  update public.lesson_files
  set
    document = p_document,
    document_version = document_version + 1,
    page_count = p_page_count,
    updated_at = now()
  where owner_id = p_owner_id and id = p_file_id
  returning * into current_file;

  insert into public.lesson_file_versions(
    owner_id,
    lesson_file_id,
    document_version,
    document,
    page_count,
    actor,
    run_id,
    idempotency_key,
    request_hash
  )
  values (
    p_owner_id,
    p_file_id,
    current_file.document_version,
    p_document,
    p_page_count,
    p_source,
    p_run_id,
    p_idempotency_key,
    request_hash
  );
  return current_file;
end
$$;

create or replace function public.apply_approved_document_patch(
  p_owner_id uuid,
  p_approval_id uuid,
  p_idempotency_key text
)
returns public.lesson_files
language plpgsql
security definer
set search_path = public
as $$
declare
  approval public.agent_approvals;
  current_file public.lesson_files;
  existing_version public.lesson_file_versions;
  operation jsonb;
  field_name text;
  source_text text;
  next_document jsonb;
begin
  perform public.assert_service_scope(p_owner_id);

  select *
  into approval
  from public.agent_approvals
  where owner_id = p_owner_id and id = p_approval_id
  for update;
  if not found then raise exception 'approval_not_found'; end if;

  select *
  into existing_version
  from public.lesson_file_versions
  where owner_id = p_owner_id and idempotency_key = p_idempotency_key;
  if found then
    if (
      existing_version.approval_id is not null
      and existing_version.approval_id <> p_approval_id
    ) or (
      existing_version.approval_id is null
      and (
        existing_version.idempotency_key <> ('approval:' || p_approval_id::text)
        or existing_version.lesson_file_id <> approval.patch->>'fileId'
        or existing_version.actor <> 'agent'
        or existing_version.run_id is distinct from approval.run_id
      )
    )
    then
      raise exception 'idempotency_conflict';
    end if;
    update public.lesson_file_versions
    set approval_id = p_approval_id
    where id = existing_version.id and approval_id is null;
    select *
    into current_file
    from public.lesson_files
    where owner_id = p_owner_id and id = existing_version.lesson_file_id;
    return current_file;
  end if;

  if approval.state <> 'pending' then raise exception 'approval_not_approvable'; end if;
  select *
  into current_file
  from public.lesson_files
  where owner_id = p_owner_id and id = approval.patch->>'fileId'
  for update;
  if not found then raise exception 'lesson_file_not_found'; end if;
  if current_file.document_version <> (approval.patch->>'baseDocumentVersion')::integer then
    raise exception 'stale_document';
  end if;

  next_document := current_file.document;
  for operation in
    select value
    from jsonb_array_elements(approval.patch->'operations')
    order by value->>'field', (value->>'start')::integer desc
  loop
    field_name := operation->>'field';
    source_text := next_document->>field_name;
    if substring(
      source_text
      from (operation->>'start')::integer + 1
      for (operation->>'end')::integer - (operation->>'start')::integer
    ) <> operation->>'expectedText'
    then
      raise exception 'text_mismatch';
    end if;
    source_text := substring(source_text from 1 for (operation->>'start')::integer)
      || (operation->>'replacement')
      || substring(source_text from (operation->>'end')::integer + 1);
    next_document := jsonb_set(next_document, array[field_name], to_jsonb(source_text), false);
  end loop;

  current_file := public.save_lesson_document(
    p_owner_id,
    current_file.id,
    current_file.document_version,
    next_document,
    current_file.page_count,
    'agent',
    approval.run_id,
    p_idempotency_key
  );
  update public.lesson_file_versions
  set approval_id = p_approval_id
  where owner_id = p_owner_id and idempotency_key = p_idempotency_key;
  update public.agent_approvals set state = 'approved' where id = p_approval_id;
  return current_file;
end
$$;

create or replace function public.append_agent_session_items(
  p_owner_id uuid,
  p_thread_id uuid,
  p_branch_id uuid,
  p_items jsonb,
  p_idempotency_key text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  next_sequence bigint;
  batch_hash text;
  existing_hash text;
begin
  perform public.assert_service_scope(p_owner_id);
  perform pg_advisory_xact_lock(
    hashtextextended(p_owner_id::text || ':' || p_thread_id::text || ':' || p_branch_id::text, 0)
  );

  if p_idempotency_key is not null then
    batch_hash := encode(extensions.digest(p_items::text, 'sha256'), 'hex');
    select payload_hash
    into existing_hash
    from public.agent_session_append_batches
    where owner_id = p_owner_id
      and thread_id = p_thread_id
      and branch_id = p_branch_id
      and idempotency_key = p_idempotency_key;
    if found then
      if existing_hash <> batch_hash then raise exception 'idempotency_conflict'; end if;
      return;
    end if;
    insert into public.agent_session_append_batches(
      owner_id,
      thread_id,
      branch_id,
      idempotency_key,
      payload_hash,
      item_count
    )
    values (
      p_owner_id,
      p_thread_id,
      p_branch_id,
      p_idempotency_key,
      batch_hash,
      jsonb_array_length(p_items)
    );
  end if;

  select coalesce(max(sequence), 0)
  into next_sequence
  from public.agent_session_items
  where owner_id = p_owner_id
    and thread_id = p_thread_id
    and branch_id = p_branch_id;

  for item in select * from jsonb_array_elements(p_items)
  loop
    next_sequence := next_sequence + 1;
    insert into public.agent_session_items(owner_id, thread_id, branch_id, sequence, item)
    values (p_owner_id, p_thread_id, p_branch_id, next_sequence, item);
  end loop;
end
$$;

create or replace function public.fork_agent_branch(
  p_owner_id uuid,
  p_thread_id uuid,
  p_parent_branch_id uuid,
  p_forked_from_message_id uuid
)
returns public.agent_branches
language plpgsql
security definer
set search_path = public
as $$
declare
  branch public.agent_branches;
  parent_branch public.agent_branches;
  fork_message public.agent_messages;
  parent_session_count bigint;
begin
  perform public.assert_service_scope(p_owner_id);

  if not exists (
    select 1
    from public.agent_threads
    where id = p_thread_id and owner_id = p_owner_id and deleted_at is null
  ) then
    raise exception 'thread_not_found';
  end if;

  select *
  into parent_branch
  from public.agent_branches
  where id = p_parent_branch_id
    and owner_id = p_owner_id
    and thread_id = p_thread_id;
  if not found then raise exception 'parent_branch_not_found'; end if;

  select *
  into fork_message
  from public.agent_messages
  where id = p_forked_from_message_id
    and owner_id = p_owner_id
    and thread_id = p_thread_id
    and branch_id = p_parent_branch_id;
  if not found then raise exception 'fork_message_scope_invalid'; end if;

  if fork_message.session_cursor is not null then
    select count(*)
    into parent_session_count
    from public.agent_session_items
    where owner_id = p_owner_id
      and thread_id = p_thread_id
      and branch_id = p_parent_branch_id;
    if parent_session_count < fork_message.session_cursor then
      raise exception 'fork_session_not_committed';
    end if;
  end if;

  insert into public.agent_branches(
    owner_id,
    thread_id,
    parent_branch_id,
    forked_from_message_id,
    label
  )
  values (
    p_owner_id,
    p_thread_id,
    p_parent_branch_id,
    p_forked_from_message_id,
    '分支'
  )
  returning * into branch;

  insert into public.agent_messages(
    owner_id,
    thread_id,
    branch_id,
    role,
    content,
    status,
    sources,
    session_cursor,
    created_at
  )
  select
    owner_id,
    thread_id,
    branch.id,
    role,
    content,
    status,
    sources,
    session_cursor,
    created_at
  from public.agent_messages
  where owner_id = p_owner_id
    and thread_id = p_thread_id
    and branch_id = p_parent_branch_id
    and sequence <= fork_message.sequence
  order by sequence;

  if fork_message.session_cursor is not null then
    insert into public.agent_session_items(
      owner_id,
      thread_id,
      branch_id,
      sequence,
      item,
      created_at
    )
    select
      p_owner_id,
      p_thread_id,
      branch.id,
      sequence,
      item,
      created_at
    from public.agent_session_items
    where owner_id = p_owner_id
      and thread_id = p_thread_id
      and branch_id = p_parent_branch_id
      and sequence <= fork_message.session_cursor
    order by sequence;

    insert into public.agent_thread_memories(
      owner_id,
      thread_id,
      branch_id,
      summary,
      summary_cursor,
      updated_at
    )
    select
      p_owner_id,
      p_thread_id,
      branch.id,
      summary,
      summary_cursor,
      updated_at
    from public.agent_thread_memories
    where owner_id = p_owner_id
      and thread_id = p_thread_id
      and branch_id = p_parent_branch_id
      and summary_cursor <= fork_message.session_cursor;
  else
    insert into public.agent_session_items(
      owner_id,
      thread_id,
      branch_id,
      sequence,
      item
    )
    select
      p_owner_id,
      p_thread_id,
      branch.id,
      row_number() over (order by sequence),
      jsonb_build_object('type', 'message', 'role', role, 'content', content)
    from public.agent_messages
    where owner_id = p_owner_id
      and thread_id = p_thread_id
      and branch_id = branch.id
    order by sequence;
  end if;

  return branch;
end
$$;

create or replace function public.decide_agent_approval(
  p_owner_id uuid,
  p_approval_id uuid,
  p_approved boolean,
  p_encrypted_run_state text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  approval public.agent_approvals;
  file public.lesson_files;
  desired_state text;
begin
  perform public.assert_service_scope(p_owner_id);
  desired_state := case when p_approved then 'approved' else 'rejected' end;

  select *
  into approval
  from public.agent_approvals
  where owner_id = p_owner_id and id = p_approval_id
  for update;
  if not found then raise exception 'approval_not_found'; end if;
  if approval.expires_at <= now() or approval.state = 'expired' then raise exception 'approval_expired'; end if;
  if approval.state <> 'pending' and approval.state <> desired_state then
    raise exception 'approval_already_resolved';
  end if;

  if approval.state = 'pending' then
    if p_approved then
      file := public.apply_approved_document_patch(
        p_owner_id,
        p_approval_id,
        'approval:' || p_approval_id::text
      );
    else
      update public.agent_approvals
      set state = 'rejected'
      where owner_id = p_owner_id and id = p_approval_id;
    end if;
  elsif p_approved then
    select *
    into file
    from public.lesson_files
    where owner_id = p_owner_id and id = approval.patch->>'fileId';
  end if;

  update public.agent_approvals
  set
    encrypted_run_state = p_encrypted_run_state,
    continuation_status = case
      when continuation_status = 'completed' then 'completed'
      else 'ready'
    end,
    continuation_lease_token = null,
    continuation_lease_expires_at = null,
    continuation_error = null,
    continuation_message_id = coalesce(continuation_message_id, gen_random_uuid())
  where owner_id = p_owner_id and id = p_approval_id
  returning * into approval;

  return jsonb_build_object('approval', to_jsonb(approval), 'file', to_jsonb(file));
end
$$;

create or replace function public.claim_agent_approval_continuation(
  p_owner_id uuid,
  p_approval_id uuid,
  p_lease_token text,
  p_lease_expires_at timestamptz
)
returns public.agent_approvals
language plpgsql
security definer
set search_path = public
as $$
declare
  approval public.agent_approvals;
begin
  perform public.assert_service_scope(p_owner_id);
  select *
  into approval
  from public.agent_approvals
  where owner_id = p_owner_id and id = p_approval_id
  for update;
  if not found then raise exception 'approval_not_found'; end if;
  if approval.state = 'pending' then raise exception 'approval_decision_missing'; end if;
  if approval.continuation_status = 'completed' then return approval; end if;
  if approval.continuation_status = 'running'
    and approval.continuation_lease_expires_at > now()
  then
    raise exception 'active_run_exists';
  end if;

  update public.agent_approvals
  set
    continuation_status = 'running',
    continuation_lease_token = p_lease_token,
    continuation_lease_expires_at = p_lease_expires_at,
    continuation_attempt_count = continuation_attempt_count + 1,
    continuation_error = null,
    continuation_message_id = coalesce(continuation_message_id, gen_random_uuid())
  where owner_id = p_owner_id and id = p_approval_id
  returning * into approval;
  return approval;
end
$$;

create or replace function public.finish_agent_approval_continuation(
  p_owner_id uuid,
  p_approval_id uuid,
  p_lease_token text,
  p_status text,
  p_error text
)
returns public.agent_approvals
language plpgsql
security definer
set search_path = public
as $$
declare
  approval public.agent_approvals;
begin
  perform public.assert_service_scope(p_owner_id);
  if p_status not in ('ready', 'completed') then raise exception 'invalid_continuation_status'; end if;
  select *
  into approval
  from public.agent_approvals
  where owner_id = p_owner_id and id = p_approval_id
  for update;
  if not found then raise exception 'approval_not_found'; end if;
  if approval.continuation_status = 'completed' then return approval; end if;
  if approval.continuation_status <> 'running'
    or approval.continuation_lease_token is distinct from p_lease_token
  then
    raise exception 'approval_lease_lost';
  end if;

  update public.agent_approvals
  set
    continuation_status = p_status,
    continuation_lease_token = null,
    continuation_lease_expires_at = null,
    continuation_error = p_error
  where owner_id = p_owner_id and id = p_approval_id
  returning * into approval;
  return approval;
end
$$;

